#!/usr/bin/env bash
# up.sh — one-command local Zcash dev chain (Zebra regtest + light-wallet gRPC + funded wallets).
#
#   ./up.sh                       # profile "ironwood" (mainnet-like: NU6.3 active), reuse state if present
#   ./up.sh --fresh               # wipe this profile's chain + wallets first
#   ./up.sh --profile transition  # Orchard era until height 300, then NU6.3/Ironwood
#   ./up.sh --profile orchard     # NU6.2 is the last upgrade: Orchard behaves like pre-2026-07-28 mainnet
#   ./up.sh --indexer zaino       # put zainod in front of zebrad (default: zebra's built-in lightwalletd gRPC)
#   ./up.sh --wallets "alice bob carol"
#
# Afterwards:  source .data/<profile>/env.sh   (exports ZEBRA_RPC, LWD, addresses, helper functions)
# Stop:        ./down.sh            (keep data)     ./down.sh --clean   (wipe everything)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROFILE=ironwood
FRESH=0
INDEXER=zebra
WALLETS="alice bob"
RPC_PORT=${RPC_PORT:-18232}
LWD_PORT=${LWD_PORT:-9067}          # zebra built-in CompactTxStreamer (or zaino's gRPC when --indexer zaino)
P2P_PORT=${P2P_PORT:-18233}
INDEXER_PORT=${INDEXER_PORT:-8230}  # zebra's indexer gRPC (used by zaino)
SHIELDED_CB_PER_WALLET=${SHIELDED_CB_PER_WALLET:-2}   # x2 coinbases when FUNDING=shield (default)
# NB regtest subsidy: 6.25 ZEC/block, halving every 288 blocks (first at 287) -> ~3600 ZEC ever. Fund early.
TRANSPARENT_CB_PER_WALLET=${TRANSPARENT_CB_PER_WALLET:-1}

while [ $# -gt 0 ]; do
  case "$1" in
    --profile) PROFILE="$2"; shift 2;;
    --fresh) FRESH=1; shift;;
    --indexer) INDEXER="$2"; shift 2;;
    --wallets) WALLETS="$2"; shift 2;;
    -h|--help) sed -n 2,14p "$0"; exit 0;;
    *) echo "unknown arg $1"; exit 2;;
  esac
done

HEIGHTS="$ROOT/config/heights-$PROFILE.toml"
[ -f "$HEIGHTS" ] || { echo "no such profile: $HEIGHTS"; exit 2; }
DATA="$ROOT/.data/$PROFILE"
BIN="$ROOT/.tools/bin"
ZEBRAD="${ZEBRAD:-$BIN/zebrad}"   # override e.g. ZEBRAD=.tools7/bin/zebrad for the nu7 profile
DEVTOOL="$BIN/zcash-devtool"
ZAINOD="$BIN/zainod"
ZEBRA_VERSION=6.4.2
DEVTOOL_REV=5a26ee854e634a4e88d1d79dab13f8fbb1eac6b8   # zcash/zcash-devtool main @ 2026-08-28
ZAINO_VERSION=0.10.2

tmo() { local t=$1; shift; perl -e 'alarm shift; exec @ARGV' "$t" "$@"; }   # macOS has no `timeout`
log() { printf '\033[1;35m[up]\033[0m %s\n' "$*"; }
now() { python3 -c 'import time; print(time.time())'; }
since() { python3 -c "import time; print(f'{time.time()-$1:.1f}s')"; }

# ---------------------------------------------------------------- 0. binaries
export CARGO_BUILD_JOBS=${CARGO_BUILD_JOBS:-4}
[ -f "$HOME/.cargo/env" ] && source "$HOME/.cargo/env"
mkdir -p "$BIN"
if [ ! -x "$ZEBRAD" ]; then
  log "building zebrad $ZEBRA_VERSION (first run only, ~12 min on an M-series laptop; needs protoc + clang)"
  cargo install --locked "zebrad@$ZEBRA_VERSION" --root "$ROOT/.tools" --target-dir "$ROOT/target"
fi
if [ ! -x "$DEVTOOL" ]; then
  log "building zcash-devtool @${DEVTOOL_REV:0:8} with regtest_support (first run only, ~7 min)"
  cargo install --locked --git https://github.com/zcash/zcash-devtool --rev "$DEVTOOL_REV" \
    --features regtest_support --root "$ROOT/.tools" --target-dir "$ROOT/target-devtool"
fi
if [ "$INDEXER" = zaino ] && [ ! -x "$ZAINOD" ]; then
  log "building zainod $ZAINO_VERSION (first run only)"
  cargo install --locked "zainod@$ZAINO_VERSION" --root "$ROOT/.tools" --target-dir "$ROOT/target-zaino"
fi

# ---------------------------------------------------------------- 1. config
if pgrep -f "zebrad -c $ROOT/.data/" >/dev/null; then
  echo "a zebrad from this workspace is already running — run ./down.sh first"; exit 1
fi
[ "$FRESH" = 1 ] && { log "wiping $DATA"; rm -rf "$DATA"; }
mkdir -p "$DATA/wallets" "$DATA/logs"
# zcash-devtool (no zcash_unstable="nu7" build) rejects an `nu7` key, so wallets get the file minus nu7.
grep -v '^nu7' "$HEIGHTS" > "$DATA/devtool-heights.toml"

# translate the shared heights file (devtool key format) into zebrad's [activation_heights] table
ZEBRA_HEIGHTS=$(python3 - "$HEIGHTS" <<'PY'
import sys  # flat `key = value` file; no tomllib so macOS's stock python3 (3.9) works
names = {"overwinter": "Overwinter", "sapling": "Sapling", "blossom": "Blossom", "heartwood": "Heartwood",
         "canopy": "Canopy", "nu5": "NU5", "nu6": "NU6", "nu6_1": "NU6.1", "nu6_2": "NU6.2", "nu6_3": "NU6.3",
         "nu7": "NU7"}
for line in open(sys.argv[1]):
    line = line.split("#", 1)[0].strip()
    if "=" not in line: continue
    k, v = (s.strip() for s in line.split("=", 1))
    if v.strip('"') != "never":
        print(f'"{names[k]}" = {int(v)}')
PY
)

cat > "$DATA/zebrad.toml" <<EOF
# generated by up.sh (profile: $PROFILE) — edit config/heights-$PROFILE.toml instead
[network]
network = "Regtest"
listen_addr = "127.0.0.1:$P2P_PORT"
cache_dir = false            # don't write a peer cache under ~/Library/Caches/zebra

[network.testnet_parameters.activation_heights]
$ZEBRA_HEIGHTS

[rpc]
listen_addr = "127.0.0.1:$RPC_PORT"
enable_cookie_auth = false
indexer_listen_addr = "127.0.0.1:$INDEXER_PORT"
$( [ "$INDEXER" = zebra ] && echo "lightwalletd_listen_addr = \"127.0.0.1:$LWD_PORT\"" )

[state]
cache_dir = "$DATA/zebra"

[mining]
# 'generate' pays here; it is a burn address. Fund wallets with generatetoaddress instead.
miner_address = "t27eWDgjFYJGVXmzrXeVjnb5J3uXDM9xH9v"

[tracing]
filter = "info"
EOF

# ---------------------------------------------------------------- 2. start zebrad
rpc() { curl -s -m 600 -H 'content-type: application/json' \
  --data "{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"$1\",\"params\":${2:-[]}}" "127.0.0.1:$RPC_PORT"; }
rpc_result() { rpc "$@" | python3 -c 'import sys,json; r=json.load(sys.stdin); e=r.get("error"); print(json.dumps(r["result"]) if not e else sys.exit("RPC error: "+str(e)))'; }

T0=$(now)
log "starting zebrad (profile $PROFILE, RPC 127.0.0.1:$RPC_PORT)"
nohup "$ZEBRAD" -c "$DATA/zebrad.toml" start > "$DATA/logs/zebrad.log" 2>&1 < /dev/null &
echo $! > "$DATA/zebrad.pid"
for _ in $(seq 1 60); do rpc getblockcount 2>/dev/null | grep -q result && break; sleep 0.5; done
rpc getblockcount | grep -q result || { echo "zebrad did not start; see $DATA/logs/zebrad.log"; exit 1; }
log "zebrad up in $(since "$T0")"

HEIGHT=$(rpc_result getblockcount)
if [ "$HEIGHT" = 0 ]; then
  # Mine block 1 so that wallets can use birthday 2: zebra's lightwalletd gRPC rejects a
  # BlockID of height 0 ("block id must specify a hash or a height"), and wallets ask for the
  # tree state at birthday-1.
  rpc_result generate '[1]' >/dev/null
fi

# ---------------------------------------------------------------- 3. indexer
LWD="127.0.0.1:$LWD_PORT"
if [ "$INDEXER" = zaino ]; then
  cat > "$DATA/zainod.toml" <<EOF
backend = 'rpc'
network = 'Regtest'
zebra_db_path = '$DATA/zebra'
[grpc_settings]
listen_address = '127.0.0.1:$LWD_PORT'
[validator_settings]
validator_grpc_listen_address = '127.0.0.1:$INDEXER_PORT'
validator_jsonrpc_listen_address = '127.0.0.1:$RPC_PORT'
validator_user = 'xxxxxx'
validator_password = 'xxxxxx'
[storage.database]
path = '$DATA/zaino'
size = 4
sync_write_batch_size = 1
accumulator_rebuild_memory_size = 1
# flush zaino's bulk-sync batches quickly (default 120 s); harmless on a tiny local chain
sync_checkpoint_interval = 1
EOF
  log "starting zainod on $LWD"
  nohup "$ZAINOD" start -c "$DATA/zainod.toml" > "$DATA/logs/zainod.log" 2>&1 < /dev/null &
  echo $! > "$DATA/zainod.pid"
  # zainod opens its port before it can answer; requests sent too early hang forever. Wait for its
  # own status line to report the gRPC server Ready.
  for _ in $(seq 1 240); do grep -q -E 'grpc.{0,40}Ready' "$DATA/logs/zainod.log" 2>/dev/null && break; sleep 0.5; done
  grep -q -E 'grpc.{0,40}Ready' "$DATA/logs/zainod.log" || { echo "zainod not ready; see $DATA/logs/zainod.log"; exit 1; }
fi
for _ in $(seq 1 60); do nc -z 127.0.0.1 "$LWD_PORT" 2>/dev/null && break; sleep 0.5; done

# ---------------------------------------------------------------- 4. wallets
dt() { "$DEVTOOL" wallet -w "$DATA/wallets/$1" "${@:2}" 2>&1 | grep -v -E '^\S*\s*\S*INFO' || true; }
for w in $WALLETS; do
  if [ ! -f "$DATA/wallets/$w/keys.toml" ]; then
    log "creating wallet $w"
    # `init` READS A MNEMONIC FROM STDIN when stdin is not a TTY (empty line => generate). If stdin is an
    # open pipe (CI, agent harnesses, `curl | sh`, IDE tasks) it blocks forever -> always feed /dev/null.
    for attempt in 1 2 3; do
      rm -rf "$DATA/wallets/$w" "$DATA/wallets/$w.age"
      tmo 10 "$DEVTOOL" wallet -w "$DATA/wallets/$w" init --name "$w" -i "$DATA/wallets/$w.age" -n regtest \
        --activation-heights "$DATA/devtool-heights.toml" -s "$LWD" --birthday 2 </dev/null >>"$DATA/logs/wallet.log" 2>&1 && break
      log "wallet init attempt $attempt timed out/failed; retrying"
    done
    M=$("$DEVTOOL" wallet -w "$DATA/wallets/$w" display-mnemonic --enable -i "$DATA/wallets/$w.age" 2>/dev/null | tail -1)
    "$DEVTOOL" wallet derive-address --mnemonic "$M" -n regtest 2>/dev/null > "$DATA/wallets/$w.addr"
    "$DEVTOOL" wallet -w "$DATA/wallets/$w" list-accounts 2>/dev/null | awk '/UFVK:/{print $2}' > "$DATA/wallets/$w.ufvk"
    NEW_WALLETS="${NEW_WALLETS:-} $w"
  fi
done
# The indexer (zaino especially) can lag zebra right after a burst of `generate`; a wallet that syncs
# against a stale tip thinks coinbase is still immature and `shield` fails. Wait for the indexer.
wait_indexer() {   # poll the same call the wallet uses (GetLatestBlock, via `sync`), not GetLightdInfo:
  local want; want=$(rpc_result getblockcount); local first; first=$(echo $WALLETS | awk '{print $1}')
  for _ in $(seq 1 240); do   # zaino answers GetLightdInfo from zebra but GetLatestBlock from its own (lagging) index
    tip=$(tmo 30 "$DEVTOOL" wallet -w "$DATA/wallets/$first" sync -s "$LWD" 2>&1 | sed -n 's/.*Latest block height is \([0-9]*\).*/\1/p' | tail -1)
    [ "${tip:-0}" -ge "$want" ] && return 0; sleep 0.5
  done; echo "indexer did not reach height $want"; }
ua()   { awk '/Unified Address/{print $3}' "$DATA/wallets/$1.addr"; }
taddr(){ awk '/Transparent Address/{print $3}' "$DATA/wallets/$1.addr"; }

# ---------------------------------------------------------------- 5. fund new wallets
# Default funding = transparent coinbase -> `shield`.  We deliberately do NOT pay coinbase straight to
# the UA (shielded coinbase) by default: zebra's generate/generatetoaddress put a RANDOM 512-byte memo
# on shielded coinbase outputs, and zcash-devtool's `list-tx` then dies with "Invalid UTF-8".
# FUNDING=shielded-coinbase restores the direct path (faster, but breaks list-tx for that wallet).
FUNDING=${FUNDING:-shield}
if [ -n "${NEW_WALLETS:-}" ]; then
  T1=$(now)
  for w in $NEW_WALLETS; do
    if [ "$FUNDING" = shielded-coinbase ]; then
      log "funding $w: $SHIELDED_CB_PER_WALLET shielded coinbase(s) straight to its UA"
      rpc_result generatetoaddress "[$SHIELDED_CB_PER_WALLET, \"$(ua "$w")\"]" >/dev/null
    else
      log "funding $w: $((SHIELDED_CB_PER_WALLET*2)) transparent coinbase(s) to its t-addr (to be shielded)"
      rpc_result generatetoaddress "[$((SHIELDED_CB_PER_WALLET*2)), \"$(taddr "$w")\"]" >/dev/null
    fi
  done
  log "mining 100 blocks for coinbase maturity"
  rpc_result generate '[100]' >/dev/null
  if [ "$FUNDING" != shielded-coinbase ]; then
    wait_indexer
    for w in $NEW_WALLETS; do
      "$DEVTOOL" wallet -w "$DATA/wallets/$w" sync -s "$LWD" >>"$DATA/logs/wallet.log" 2>&1
      log "shielding $w's coinbase (Halo2 proving, ~10 s)"
      "$DEVTOOL" wallet -w "$DATA/wallets/$w" shield -i "$DATA/wallets/$w.age" -s "$LWD" 2>&1 | tee -a "$DATA/logs/wallet.log" \
        | grep -E '^[0-9a-f]{64}$' | sed "s/^/[up]   $w shield txid /" || echo "shield failed for $w (see $DATA/logs/wallet.log)"
    done
  fi
  for w in $NEW_WALLETS; do   # leave some transparent coinbase too, for t-addr experiments
    rpc_result generatetoaddress "[$TRANSPARENT_CB_PER_WALLET, \"$(taddr "$w")\"]" >/dev/null
  done
  log "mining 100 more blocks (mature the transparent leftovers, confirm the shields)"
  rpc_result generate '[100]' >/dev/null
  log "funding done in $(since "$T1")"
fi

# ---------------------------------------------------------------- 6. sync + report
T2=$(now)
wait_indexer
for w in $WALLETS; do "$DEVTOOL" wallet -w "$DATA/wallets/$w" sync -s "$LWD" >>"$DATA/logs/wallet.log" 2>&1 || echo "sync failed for $w"; done
log "wallet sync in $(since "$T2")"

cat > "$DATA/env.sh" <<EOF
# source me:  source $DATA/env.sh
export ZEC_PROFILE=$PROFILE
export ZEBRA_RPC=http://127.0.0.1:$RPC_PORT
export LWD=$LWD
export ZEC_DATA=$DATA
export PATH="$BIN:$ROOT/scripts:\$PATH"
$(for w in $WALLETS; do W=$(echo "$w" | tr a-z A-Z); echo "export ${W}_UA=$(ua "$w")"; echo "export ${W}_TADDR=$(taddr "$w")"; echo "export ${W}_UFVK=$(cat "$DATA/wallets/$w.ufvk")"; done)
zrpc() { curl -s -H 'content-type: application/json' --data "{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"\$1\",\"params\":\${2:-[]}}" \$ZEBRA_RPC; echo; }
mine() { zrpc generate "[\${1:-1}]" >/dev/null && zrpc getblockcount; }
# wallet <name> <devtool wallet subcommand...>   e.g.  wallet alice send --address \$BOB_UA --value 100000 --memo hi
wallet() { local w=\$1 c=\$2; shift 2; case "\$c" in
  send|shield|propose|pay) zcash-devtool wallet -w \$ZEC_DATA/wallets/\$w \$c -i \$ZEC_DATA/wallets/\$w.age -s \$LWD "\$@";;
  sync|enhance|init-fvk|get-info) zcash-devtool wallet -w \$ZEC_DATA/wallets/\$w \$c -s \$LWD "\$@";;
  *) zcash-devtool wallet -w \$ZEC_DATA/wallets/\$w \$c "\$@";; esac 2>&1 | grep -v ' INFO '; }
# viewwallet <name> <UFVK>  — watch-only wallet. init-fvk has no --activation-heights flag and silently
# uses devtool's built-in regtest heights, so we patch keys.toml with this profile's heights afterwards.
viewwallet() { zcash-devtool wallet -w \$ZEC_DATA/wallets/\$1 init-fvk --name \$1 --fvk \$2 --birthday 2 -s \$LWD 2>&1 | grep -v ' INFO ';
  sed -i '' '/^\[activation_heights\]/,\$d' \$ZEC_DATA/wallets/\$1/keys.toml;
  { echo '[activation_heights]'; grep -E '^[a-z0-9_]+ *=' $DATA/devtool-heights.toml; } >> \$ZEC_DATA/wallets/\$1/keys.toml; }
EOF

echo
log "chain '$PROFILE' ready at height $(rpc_result getblockcount)   (total $(since "$T0"))"
echo "   zebra JSON-RPC : http://127.0.0.1:$RPC_PORT  (no auth)"
echo "   light-wallet   : $LWD  (CompactTxStreamer gRPC, plaintext, served by $INDEXER)"
for w in $WALLETS; do
  B=$("$DEVTOOL" wallet -w "$DATA/wallets/$w" balance 2>/dev/null | awk '/^ *Balance:/{print $2}')
  echo "   $w: balance $B REG   UA $(ua "$w" | cut -c1-24)…  t-addr $(taddr "$w")"
done
echo "   next: source $DATA/env.sh ; wallet alice send --address \$BOB_UA --value 100000000 --memo 'hi' ; mine 1"
